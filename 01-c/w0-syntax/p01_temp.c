//摄氏 → 华氏（`F = C*9/5 + 32`），输入-40，0，37，100，结果保留一位小数
#include <stdio.h>
int main()
{
    float F = 0;
    int C = 0;
    scanf("%d",&C);
    /*
    注意：会先算出 "=" 右边的结果，最后才赋值
    只有当两边都是整数时才做整数除法，只要有一个是浮点，就做浮点除法。
    F = C * 9 / 5 +32;   //-40.0  32.0  98.0  212.0
    F = 9 / 5 *C +32;    //-8.0  32.0  69.0  132.0
    */
    F = 9.0 / 5 *C +32;     //-40.0  32.0  98.6  212.0
    
    printf("%.1f\n",F);
    return 0;
}