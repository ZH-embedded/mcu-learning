/* p09_priority.c —— 运算符优先级陷阱（参考实现）
 *
 * 这个文件故意保留了两处警告，因为它们本身是知识点：
 *   - 第 2 条会触发 -Wparentheses：编译器在提醒你 `x & 1 == 0` 可能不是你以为的意思
 *   - 第 3 条是未定义行为（UB），不同编译器/不同优化级别结果可能不同
 * 先自己写预测，再看输出；猜错的才是今天真正的收获。
 */
#include <stdio.h>

int main(void)
{
    /* 1) 连续赋值：右结合，(a = (b = (c + 1)))，表达式的值是最后赋的那个 */
    {
        int a = 0, b = 0, c = 3;
        int r = (a = b = c + 1);
        printf("1) a = b = c + 1     → a=%d b=%d 表达式值=%d\n", a, b, r);
    }

    /* 2) 关系运算优先级高于位与：x & 1 == 0 实际是 x & (1 == 0) = x & 0 = 0 */
    {
        int x = 4;
        printf("2) x & 1 == 0        → %d （实际被解释成 x & (1==0)，恒为 0）\n",
               x & 1 == 0);
        printf("   正确写法 (x & 1) == 0 → %d\n", (x & 1) == 0);
    }

    /* 3) 未定义行为：同一个变量在同一个表达式里被改两次，求值顺序未定义 */
    {
        volatile int i = 1;
        int v = i++ + ++i;             /* UB！不要在任何真实代码里写这个 */
        printf("3) i++ + ++i          → %d （UB，本机是它，别依赖）\n", v);
    }

    /* 4) 三元运算符右结合：a > b ? a : (b > c ? b : c)，等价于取最大值 */
    {
        int a = 1, b = 5, c = 3;
        printf("4) a > b ? a : b > c ? b : c → %d\n", a > b ? a : b > c ? b : c);
    }

    /* 5) 加法优先级高于移位：1 << (2 + 3) = 32 */
    printf("5) 1 << 2 + 3          → %d （是 1<<5，不是 (1<<2)+3=7）\n", 1 << 2 + 3);

    /* 6) 位或的优先级高于逻辑与：4 | 0 && 3 实际是 (4|0) && 3 = 1
     *    反直觉的地方在于：位运算（& ^ |）全都排在 && 和 || 前面 */
    {
        int a = 4, b = 0, c = 3;
        printf("6) 4 | 0 && 3          → %d （是 (4|0)&&3 = 1，不是 4|(0&&3) = 4）\n",
               a | b && c);
    }

    /* 7) 后置 ++ 与解引用：*p++ 是 *(p++)，先取当前值再移动指针 */
    {
        int arr[3] = { 100, 200, 300 };
        int *p = arr;
        int v = *p++;                  /* *(p++)：先取 *p，再让 p 自增 */
        printf("7) *p++                → %d，之后 p 指向 %d\n", v, *p);
        /* 注意：不能写成 printf("...", *p++, *p) ——
         * 函数参数的求值顺序未指定，*p 可能先算，结果就不确定了 */
    }

    printf("\n记忆方法：\n");
    printf("  括号 > 单目 > 算术 > 移位 > 关系 > 相等 > 位与 > 位异或 > 位或 > 逻辑与 > 逻辑或 > 三目 > 赋值 > 逗号\n");
    printf("  实际工作中：拿不准就加括号，加括号不丢人，猜错优先级才会出事\n");

    return 0;
}
